"""Per-file headers, as the original was organized: every source file (one link unit, i.e.
one original translation unit, or one standalone data/assembler file) declares what it
defines in src/include/<STEM>.H, and each C source includes the headers of the files whose
globals and functions it uses. Declarations still come from the DB (`./sr global`,
`./sr proto`); ownership comes from where the definition is.

GLOBALS.H and PROTOS.H are still generated for the check scaffolding (.STB stubs)."""
import json
import re
from pathlib import Path

from . import config
from .headers import _write

_BANNER = ("/* {name} - declarations of what {owner} define(s).\n"
           "   Generated by `./sr headers` from db/sr.sqlite and the definitions in the sources.\n"
           "   DO NOT EDIT: use `./sr global` / `./sr proto`. */\n")
_INC = re.compile(r'^#include\s+"(GLOBALS|PROTOS|STRUCTS)\.H"\s*$|^#include\s+"[A-Z0-9_]+\.H"\s*/\*\s*file\s*\*/\s*$', re.M)
_KEEP = {'GLOBALS', 'PROTOS', 'STRUCTS', 'CRT'}
# runtime variables the game reads directly; MSC's own headers declare them
_SYSTEM = {'errno': 'stdlib.h', '_doserrno': 'stdlib.h', '_amblksiz': 'malloc.h'}


def owners_layout():
    """[(stem, [source paths])] for every original file: link units, then standalone files."""
    plan = json.loads((config.SRC / 'link' / 'LAYOUT.JSON').read_text())
    out, seen = [], set()
    for u in plan['units'] + plan.get('data_units', []):
        srcs = [config.ROOT / s for s in u['sources']]
        out.append((srcs[0].stem.upper(), srcs)); seen.update(srcs)
    for p in sorted([*(config.SRC / 'data').glob('*.[CA]*'), *(config.SRC / 'link').glob('*.ASM')]):
        if p.suffix.upper() in ('.C', '.ASM') and p not in seen:
            out.append((p.stem.upper(), [p]))
    return out


def _strip(text):
    text = re.sub(r'/\*.*?\*/', ' ', text, flags=re.S)
    return re.sub(r'"(\\.|[^"\\])*"|\'(\\.|[^\'\\])*\'', '""', text)


def _defines(path, names):
    """Names from `names` that this source defines (C file-scope definitions, MASM PUBLICs)."""
    text = _strip(path.read_text(encoding='latin-1'))
    if path.suffix.upper() == '.ASM':
        pubs = {m.lower() for m in re.findall(r'^\s*PUBLIC\s+_(\w+)', text, re.M | re.I)}
        return {n for n in names if n.lower() in pubs}
    found = set()
    for ln in text.splitlines():
        if not ln[:1].isalpha() or ln.startswith(('extern', 'static', 'typedef')):
            continue
        ln = ln.split("=")[0]
        for m in re.finditer(r'\b([A-Za-z_]\w*)\b', ln):
            n = m.group(1)
            if n not in names:
                continue
            rest = ln[m.end():]
            # data: `T n;`, `T n[..] = ...`, `T (far *n)(...);`; function: `T n(args)` without `;`
            if re.match(r"\s*(\[[^]]*\]\s*)*(=|;|,|$)", rest) or re.match(r'\s*(\[[^]]*\]\s*)*\)\s*\(', rest) \
                    or (re.match(r'\s*\(', rest) and not ln.rstrip().endswith(';')):
                found.add(n)
                break
    return found


def generate(con, rewrite_sources=False):
    glob = {g['name']: (g['off'], f"extern {g['decl'].replace('@', g['name'])};", f"DS:{g['off']:04X}")
            for g in con.execute("SELECT off, name, decl FROM globals WHERE decl IS NOT NULL")}
    far = {g['name']: ((g['seg'] << 16) | g['off'], f"extern {g['decl'].replace('@', g['name'])};",
                       f"{g['seg']:04X}:{g['off']:04X}")
           for g in con.execute("SELECT seg, off, name, decl FROM fardata WHERE decl IS NOT NULL")}
    funcs = {}
    for f in con.execute("SELECT addr, name, proto FROM functions WHERE proto IS NOT NULL AND (far = 1 OR proto LIKE "
                         "'%interrupt%' OR proto LIKE '%far @%') AND kind != 'crt'"):
        n = f['name'] or f"F_{f['addr']:05X}"
        funcs[n] = (f['addr'], f"{f['proto'].replace('@', n)};", f"0x{f['addr']:05X}")
    names = set(glob) | set(far) | set(funcs)
    owner, files = {}, owners_layout()
    for stem, srcs in files:
        for p in srcs:
            for n in _defines(p, names):
                if n in owner and owner[n] != stem:
                    raise SystemExit(f'{n} is defined in both {owner[n]} and {stem}')
                owner[n] = stem
    inc = config.INCLUDE
    made = set()
    for stem, srcs in files:
        mine = [n for n in names if owner.get(n) == stem]
        if not mine:
            continue
        out = [_BANNER.format(name=f'{stem}.H', owner=', '.join(p.name for p in srcs)),
               f'#ifndef {stem}_H', f'#define {stem}_H', '#include "STRUCTS.H"', '']
        for table in (glob, far, funcs):
            for n in sorted((n for n in mine if n in table), key=lambda n: table[n][0]):
                out.append(table[n][1].ljust(56) + f'/* {table[n][2]} */')
        out += ['', '#endif', '']
        _write(inc / f'{stem}.H', '\n'.join(out))
        made.add(stem)
    for p in inc.glob('*.H'):          # headers of files that no longer define anything
        if p.stem.upper() not in made | _KEEP and p.read_text(errors='replace').startswith('/* ' + p.name + ' - what'):
            p.unlink()
    missing = sorted(n for n in names if n not in owner and n not in _SYSTEM)
    if rewrite_sources:
        for stem, srcs in files:
            for p in srcs:
                if p.suffix.upper() == '.C':
                    _rewrite_includes(p, stem, owner, made)
    return missing


def _rewrite_includes(path, stem, owner, made):
    raw = path.read_text(encoding='latin-1')
    ids = set(re.findall(r'\b[A-Za-z_]\w*\b', _strip(raw)))
    need = sorted({owner[i] for i in ids if i in owner} & made - {stem})
    block = ['#include "STRUCTS.H"'] + ([f'#include "{stem}.H"'] if stem in made else []) + [f'#include "{h}.H"' for h in need]
    lines = raw.split('\n')
    for h in sorted({_SYSTEM[i] for i in ids if i in _SYSTEM}):
        if not re.search(rf'^#include\s+<{re.escape(h)}>', raw, re.M | re.I):
            k = max((i for i, ln in enumerate(lines) if ln.startswith('#include <')), default=-1)
            lines.insert(k + 1, f'#include <{h}>')
    at = [i for i, ln in enumerate(lines) if re.match(r'#include\s+"(GLOBALS|PROTOS|STRUCTS)\.H"', ln)
          or (re.match(r'#include\s+"(\w+)\.H"', ln) and re.match(r'#include\s+"(\w+)\.H"', ln).group(1) not in _KEEP)]
    if not at:
        raise SystemExit(f'{path}: no header include block to rewrite')
    new = lines[:at[0]] + block + [ln for i, ln in enumerate(lines) if i > at[0] and i not in at]
    text = '\n'.join(new)
    if text != raw:
        path.write_text(text, encoding='latin-1')
