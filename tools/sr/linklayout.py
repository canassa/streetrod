"""`./sr build`: run the checked-in build, src/MAKEFILE and src/SR.LNK, with the original tools,
then verify the result against the original.

The build needs only src/ and toolchain/. work/layout is a copy of src/, the developer's
directory: MAKEFILE, SR.LNK, MODS\\, DATA\\ and INCLUDE\\. Every description block of the
MAKEFILE runs exactly as written, in its own copy of that tree (work/layout/BUILD/<stem>):
LIB and each object's CL or MASM line under emu2, in parallel; then the link block's LINK
line in DOSBox-X, which reads SR.LNK. Nothing is generated: the objects, their command lines
and the link order are the checked-in files.

The verification is separate and reads the DB and orig/: each code object is gated against
the original image (its functions are the DB rows whose `src` it is), the link is repeated
without /EXEPACK for `./sr linkcheck`, and the packed EXE is compared with orig/SR.EXE.
"""
import concurrent.futures
import shutil

from . import build, config, makefile

OUT = config.WORK/'layout'


def _check_definition(rules, lib, link, objects):
    """The MAKEFILE and SR.LNK describe one build: every object is compiled once and linked,
    and (MAKE 4.07 runs blocks in file order) the library comes first, the link last."""
    targets = [r.target for r in rules]
    if len(set(targets)) != len(targets):
        raise SystemExit('src/MAKEFILE: an object is built twice')
    if sorted(targets) != sorted(objects):
        raise SystemExit('src/SR.LNK and the objects of src/MAKEFILE differ: '
                         + ', '.join(sorted(set(targets) ^ set(objects))))
    missing = (set(objects) | {lib.target, makefile.RESPONSE.name}) - set(link.deps)
    if missing:
        raise SystemExit(f'src/MAKEFILE: {link.target} does not depend on ' + ', '.join(sorted(missing)))
    if not lib.first < min(r.first for r in rules) or not link.first > max(r.first for r in rules):
        raise SystemExit('src/MAKEFILE: MAKE runs blocks in order: the library first, the link last')
    if '@' + makefile.RESPONSE.name not in link.args:
        raise SystemExit(f'src/MAKEFILE: the link does not read {makefile.RESPONSE.name}')
    for r in rules:
        if not r.path.exists():
            raise SystemExit(f'src/MAKEFILE: {r.target}: no source {r.source}')


def prepare():
    """Copy src/ to work/layout; return the MAKEFILE's object blocks, in its order."""
    rules, lib, link = makefile.compile_rules(), makefile.rule('LIB'), makefile.rule('LINK')
    _check_definition(rules, lib, link, makefile.link_order())
    OUT.mkdir(parents=True, exist_ok=True)
    for path in OUT.iterdir():   # a fresh copy of the tree (BUILD/ is redone per job)
        if path.is_dir() and path.name != 'BUILD':
            shutil.rmtree(path)
        elif path.name in ('BUILD.BAT', 'ENV.BAT', 'LINK.RSP', 'BUILD.JSON'):
            path.unlink()        # generated by earlier versions of this build
    shutil.copytree(config.SRC, OUT, dirs_exist_ok=True)
    (OUT/'TMP').mkdir(exist_ok=True)
    return rules


def _job_root(rule):
    return OUT/'BUILD'/rule.stem


def run_block(rule):
    """One CL, MASM or LIB block, in a copy of the tree with its source and the headers.
    Returns None, or the reason it failed."""
    root = _job_root(rule)
    shutil.rmtree(root, ignore_errors=True)
    (root/'TMP').mkdir(parents=True)
    if rule.compiler:
        shutil.copytree(config.INCLUDE, root/config.INCLUDE.relative_to(config.SRC))
        source = root/rule.path.relative_to(config.SRC)
        source.parent.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(rule.path, source)
    rc = build.run_dos(root, rule.program, rule.args, root/'CC.LOG')
    if rc or not (root/rule.target).exists():
        return f'{rule.program} failed\n' + (root/'CC.LOG').read_text(errors='replace')[-2000:]
    shutil.copyfile(root/rule.target, OUT/rule.target)
    return None


def gate_objects(rules):
    """Verification: gate every code object against the original image. Returns failures."""
    from . import cod, db, module
    from .exe import image
    from .omf import Obj
    original = image()
    con = db.connect()
    rows = [dict(r) for r in con.execute("SELECT * FROM functions WHERE status='matched' ORDER BY addr")]
    by_path = {r.path: r for r in rules}
    failures = []
    built = set()
    for f in module.files():
        rule = by_path.get(f.path)
        if rule is None:
            continue
        built.add(f.rel)
        root = _job_root(rule)
        obj = Obj(root/rule.target)
        members = [m for m in rows if m['src'] == f.rel]
        if rule.compiler == 'CL':
            listing = root/(rule.stem.lower()+'.cod')
            procs = cod.parse(listing)
            obj.statics = cod.statics(listing)
        else:
            lengths = cod.asm_lengths(next(root.glob(rule.stem+'.[Ll][Ss][Tt]'), None))
            procs = [cod.from_publics(obj, module.fname(r), lengths) for r in members]
        gate = module.gate(obj, procs, original.img, members, con=con)
        if not gate.ok:
            failures.append((rule.stem, gate.line(rule.stem)))
    unbuilt = sorted({m['src'] for m in rows} - built)
    if unbuilt:
        failures.append(('MAKEFILE', 'does not compile ' + ', '.join(unbuilt)))
    con.close()
    return failures


def run(prepare_only=False, objects_only=False, verify=True):
    rules = prepare()
    lib, link = makefile.rule('LIB'), makefile.rule('LINK')
    print(f'work/layout: a copy of src/; src/MAKEFILE builds {lib.target}, {len(rules)} objects '
          f'and {link.target}', flush=True)
    if prepare_only:
        return 0
    with concurrent.futures.ThreadPoolExecutor(max_workers=12) as pool:
        results = list(pool.map(run_block, [lib, *rules]))
    failures = [(r.target, e) for r, e in zip([lib, *rules], results) if e]
    print(f'{len(results)-len(failures)}/{len(results)} MAKEFILE blocks before the link ran', flush=True)
    if not failures and verify:
        failures = gate_objects(rules)
        print(f'{len(rules)-len(failures)}/{len(rules)} objects pass their gate', flush=True)
    if failures:
        for name, error in failures:
            print(name+': '+error)
        return 1
    if objects_only:
        return 0
    exe = link.target
    ok = build.link(OUT, link.command)
    if ok:
        (OUT/exe).replace(OUT/'SRPACKED.EXE')
        print(f'{link.command}: work/layout/SRPACKED.EXE', flush=True)
    if not verify:
        build.link_report(OUT)
        return 0 if ok else 1
    # the same link without /EXEPACK, for the diagnostics (./sr linkcheck)
    ok = build.link(OUT, ' '.join(w for w in link.command.split() if w.upper() != '/EXEPACK')) and ok
    build.link_report(OUT)
    if not ok:
        (OUT/exe).unlink(missing_ok=True)
        return 1
    from .linkmatch import check
    # A successful build remains usable while the unmasked comparison is red.
    # linkcheck itself fails until the entire file is identical.
    check(OUT/exe)
    packed, shipped = OUT/'SRPACKED.EXE', config.EXE_PACKED
    a, b = packed.read_bytes(), shipped.read_bytes()
    diff = sum(x != y for x, y in zip(a, b)) + abs(len(a) - len(b))
    print(f'Packed EXE vs {shipped.relative_to(config.ROOT)}: '
          + ('IDENTICAL' if diff == 0 else f'{diff} differing bytes (size {len(a)} vs {len(b)})'))
    return 0
