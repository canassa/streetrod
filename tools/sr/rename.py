"""`./sr rename`: give a function, a global or a source file its name everywhere at once.

A symbol (function, DGROUP global or static, far data label) is renamed in the DB (its name,
and every note that mentions it) and as a whole word in the sources, the headers, the docs and
the tools (`_name` in assembler too). A source file (`M_xxxxx.C NAME.C`) is moved with git,
its functions' `src` is updated, and its stem is replaced in src/MAKEFILE, src/SR.LNK, the
docs and the tools. The headers are regenerated afterwards (`./sr headers`), which also moves
a renamed file's header and rewrites the include blocks. Names stay checked: a new name must
be a C identifier no source or DB row uses yet, ignoring case (LINK runs without /NOI).
plans/diary.md is history and is never rewritten; docs/PROGRESS.md is regenerated by
`./sr status`."""
import re
import subprocess

from . import config, db, makefile

_IDENT = re.compile(r"[A-Za-z_][A-Za-z0-9_]{0,30}")
_FILE = re.compile(r"[A-Z0-9_]{1,8}\.(C|ASM)")


def text_files():
    """Every checked-in text file that may name a symbol or a source file."""
    root = config.ROOT
    out = [p for d in ("mods", "data") for p in (config.SRC / d).iterdir()
           if p.suffix.upper() in (".C", ".ASM", ".MD")]
    out += list(config.INCLUDE.glob("*.H"))
    out += [root / "CLAUDE.md", root / "README.md"]
    out += [p for p in (root / "docs").glob("*.md") if p.name != "PROGRESS.md"]
    out += list((root / ".claude" / "skills").rglob("*.md"))
    out += list((root / "tools" / "sr").glob("*.py")) + list((root / "tests").glob("*.py"))
    return sorted(p for p in out if p.is_file())


def _pattern(names, prefix=True):
    alt = "|".join(re.escape(n) for n in sorted(names, key=len, reverse=True))
    return re.compile(rf"(?<![A-Za-z0-9_$])({'_?' if prefix else ''})({alt})(?![A-Za-z0-9_])")


def _sub(pat, mapping, text):
    return pat.sub(lambda m: m.group(1) + mapping[m.group(2)], text)


def _symbol(con, name):
    """('function', addr) | ('global', off) | ('far', (seg, off)) for a current name."""
    hits = []
    for r in con.execute("SELECT addr, name FROM functions"):
        if (r["name"] or f"F_{r['addr']:05X}") == name:
            hits.append(("function", r["addr"]))
    hits += [("global", r["off"]) for r in con.execute("SELECT off FROM globals WHERE name = ?", (name,))]
    hits += [("far", (r["seg"], r["off"])) for r in con.execute("SELECT seg, off FROM fardata WHERE name = ?", (name,))]
    if len(hits) != 1:
        raise SystemExit(f"{name}: {'no' if not hits else len(hits)} functions/globals/far data of that name")
    return hits[0]


def _taken(con, files):
    """Every name in use, upper-cased: DB names and aliases, and every identifier of the sources."""
    names = {(r["name"] or f"F_{r['addr']:05X}").upper() for r in con.execute("SELECT addr, name FROM functions")}
    names |= {r[0].upper() for r in con.execute("SELECT name FROM aliases")}
    names |= {r[0].upper() for r in con.execute("SELECT name FROM globals")}
    names |= {r[0].upper() for r in con.execute("SELECT name FROM fardata")}
    from .fileheaders import _strip
    for p in files:
        if p.suffix.upper() in (".C", ".ASM", ".H"):
            text = p.read_text(encoding="latin-1")
            # identifiers only: not the words of strings and comments
            text = re.sub(r"'[^'\n]*'|\"[^\"\n]*\"|;[^\n]*", "", text) if p.suffix.upper() == ".ASM" else _strip(text)
            for w in re.findall(r"[A-Za-z_]\w*", text):
                names.add(w.upper())
                if w.startswith("_"):
                    names.add(w[1:].upper())
    return names


def parse_pairs(lines):
    out = []
    for ln in lines:
        ln = ln.split("#")[0].strip()
        if ln:
            old, new = ln.split()
            out.append((old, new))
    return out


def rename(pairs, dry=False):
    """Apply (old, new) pairs; returns a report (list of lines)."""
    con = db.connect()
    files = text_files()
    taken = _taken(con, files)
    syms, stems, moves, report = {}, {}, [], []
    news = [n for _, n in pairs]
    if len({n.upper() for n in news}) != len(news):
        raise SystemExit("a new name appears twice")
    olds = {o for o, _ in pairs}
    for old, new in pairs:
        if new in olds:
            raise SystemExit(f"{new} is both a new and an old name: rename in two steps")
        if _FILE.fullmatch(old.upper()) and "." in old:
            if not _FILE.fullmatch(new) or new.rsplit(".", 1)[1] != old.upper().rsplit(".", 1)[1]:
                raise SystemExit(f"{new}: a source file name is DOS 8.3, upper case, same extension as {old}")
            src = next((p for d in ("mods", "data") for p in (config.SRC / d).iterdir()
                        if p.name.upper() == old.upper()), None)
            if src is None:
                raise SystemExit(f"{old}: not a file of src/mods or src/data")
            ostem, nstem = src.stem.upper(), new.rsplit(".", 1)[0]
            if any(p.stem.upper() == nstem for d in ("mods", "data") for p in (config.SRC / d).iterdir()) \
                    or (config.INCLUDE / f"{nstem}.H").exists() and nstem != ostem:
                raise SystemExit(f"{new}: a file of that name exists")
            stems[ostem] = nstem
            moves.append((src, src.with_name(new)))
            continue
        if not _IDENT.fullmatch(new):
            raise SystemExit(f"{new!r} is not a C identifier (letters, digits, _, at most 31 chars)")
        if new.upper() in taken:
            raise SystemExit(f"{new} is already used (DB or sources, ignoring case)")
        syms[old] = (new, _symbol(con, old))
    mapping = {o: n for o, (n, _) in syms.items()}
    spat = _pattern(mapping) if mapping else None
    fpat = _pattern(stems, prefix=False) if stems else None

    def fix(text):
        if spat:
            text = _sub(spat, mapping, text)
        if fpat:
            text = _sub(fpat, stems, text)
        return text

    # a moved file's old header is not edited: it goes, and `./sr headers` writes the new one
    gone = {config.INCLUDE / f"{o}.H" for o in stems}
    for p in [p for p in files if p not in gone] + [makefile.MAKEFILE, makefile.RESPONSE]:
        raw = p.read_bytes().decode("latin-1")
        new = fix(raw)
        if new != raw:
            n = (len(spat.findall(raw)) if spat else 0) + (len(fpat.findall(raw)) if fpat else 0)
            report.append(f"{p.relative_to(config.ROOT)}: {n} replacements")
            if not dry:
                p.write_bytes(new.encode("latin-1"))
    for old, (new, (kind, key)) in syms.items():
        report.append(f"{kind} {old} -> {new}")
        if dry:
            continue
        if kind == "function":
            con.execute("UPDATE functions SET name = ? WHERE addr = ?", (new, key))
        elif kind == "global":
            con.execute("UPDATE globals SET name = ? WHERE off = ?", (new, key))
        else:
            con.execute("UPDATE fardata SET name = ? WHERE seg = ? AND off = ?", (new, *key))
    for table, keycols in (("functions", ("addr",)), ("globals", ("off",)), ("fardata", ("seg", "off"))):
        for r in con.execute(f"SELECT {', '.join(keycols)}, notes FROM {table} WHERE notes IS NOT NULL").fetchall():
            fixed = fix(r["notes"])
            if fixed != r["notes"] and not dry:
                con.execute(f"UPDATE {table} SET notes = ? WHERE " + " AND ".join(f"{k} = ?" for k in keycols),
                            (fixed, *[r[k] for k in keycols]))
    for src, dst in moves:
        orel, nrel = (p.relative_to(config.ROOT).as_posix() for p in (src, dst))
        report.append(f"file {orel} -> {nrel}")
        if dry:
            continue
        subprocess.run(["git", "mv", str(src), str(dst)], cwd=config.ROOT, check=True)
        header = config.INCLUDE / f"{src.stem.upper()}.H"
        if header.exists():
            subprocess.run(["git", "rm", "-q", str(header)], cwd=config.ROOT, check=True)
        con.execute("UPDATE functions SET src = ? WHERE src = ?", (nrel, orel))
    if dry:
        con.close()
        return report
    con.commit()
    if moves:
        makefile._cache.clear()
        _rewrap_link()
    from .headers import generate
    generate(con, rewrite_sources=True)
    return report


def _rewrap_link():
    """The link block's dependency lines, wrapped again after object names changed length."""
    r = makefile.rule("LINK")
    makefile._replace(r, makefile._block(r.target, r.deps, r.raw[0]), makefile.MAKEFILE)


def static_key(name):
    """MSC 5.1's order key for a file's uninitialized statics (CLAUDE.md 4f)."""
    return sum(b & 0xDF for b in name.encode("ascii")) % 256


def fit(old, candidates):
    """Whether each candidate name keeps a placed global where it is: a communal must stay
    in its LINK hash-bucket window (CLAUDE.md 4e), a file static in its key window (4f).
    Ties with a neighbour depend on creation/declaration order: the build decides those.
    Returns lines of text."""
    from . import dgroup, fileheaders, linkhash, module
    con = db.connect()
    row = con.execute("SELECT off FROM globals WHERE name = ?", (old,)).fetchone()
    if row is None:
        return [f"{old}: not a DGROUP global; initialized data, functions and far data are placed "
                "by their definitions, not their names (only the compiler budget, 4d, counts the length)"]
    off = row["off"]
    if dgroup.COMMON_START <= off < dgroup.END:
        rows = con.execute("SELECT off, name FROM globals WHERE off >= ? AND off < ? ORDER BY off",
                           (dgroup.COMMON_START, dgroup.END)).fetchall()
        key, what = (lambda n: linkhash.bucket("_" + n)), "bucket"
    elif dgroup.BSS_START <= off < dgroup.BSS_PRIVATE_END:
        mine = next(fileheaders.file_statics(f.path) for f in module.files() if old in fileheaders.file_statics(f.path))
        rows = con.execute(f"SELECT off, name FROM globals WHERE name IN ({','.join('?' * len(mine))}) ORDER BY off",
                           tuple(mine)).fetchall()
        key, what = static_key, "key"
    else:
        return [f"{old}: initialized data (DS:{off:04X}) is placed by its definition, not its name"]
    i = [r["name"] for r in rows].index(old)
    lo = key(rows[i - 1]["name"]) if i > 0 else -1
    hi = key(rows[i + 1]["name"]) if i + 1 < len(rows) else 256
    out = [f"{old} DS:{off:04X} {what} {key(old)}; window {lo}..{hi} "
           f"({rows[i - 1]['name'] if i else '-'} .. {rows[i + 1]['name'] if i + 1 < len(rows) else '-'})"]
    for c in candidates:
        k = key(c)
        verdict = "fits" if lo < k < hi else "tie (build decides)" if k in (lo, hi) else "no"
        out.append(f"  {c:<28} {what} {k:3}  {verdict}")
    return out
