"""Generate the headers from the DB: the per-file headers the game sources include (fileheaders.py),
and GLOBALS.H / PROTOS.H, which only the check scaffolding (.STB stubs) uses. STRUCTS.H is hand-written."""

import os

from . import config

_BANNER = "/* {name} - generated by `./sr headers` from db/sr.sqlite. DO NOT EDIT: use {how}. */\n"


def generate(con):
    inc = config.INCLUDE
    inc.mkdir(parents=True, exist_ok=True)

    out = [_BANNER.format(name="GLOBALS.H", how="`./sr global`"),
           "#ifndef GLOBALS_H", "#define GLOBALS_H", '#include "STRUCTS.H"', ""]
    for g in con.execute("SELECT off, name, decl FROM globals ORDER BY off"):
        if g["decl"]:
            out.append(f"extern {g['decl'].replace('@', g['name'])};".ljust(56) + f"/* DS:{g['off']:04X} */")
        else:
            out.append(f"/* DS:{g['off']:04X} {g['name']}: no declaration yet (./sr global --decl) */")
    far = con.execute("SELECT seg, off, name, decl FROM fardata ORDER BY seg, off").fetchall()
    if far:
        out += ["", "/* far data: own segments, reached through MSC's segment constants in DGROUP */"]
    for g in far:
        if g["decl"]:
            out.append(f"extern {g['decl'].replace('@', g['name'])};".ljust(56) + f"/* {g['seg']:04X}:{g['off']:04X} */")
    out += ["", "#endif", ""]
    _write(inc / "GLOBALS.H", "\n".join(out))

    out = [_BANNER.format(name="PROTOS.H", how="`./sr proto`"),
           "#ifndef PROTOS_H", "#define PROTOS_H", '#include "STRUCTS.H"', ""]
    rows = con.execute("SELECT addr, name, proto FROM functions WHERE proto IS NOT NULL AND (far = 1 OR proto LIKE '%interrupt%' OR proto LIKE '%far @%') "
                       "AND kind != 'crt' ORDER BY addr")
    for f in rows:
        name = f["name"] or f"F_{f['addr']:05X}"
        out.append(f"{f['proto'].replace('@', name)};".ljust(56) + f"/* 0x{f['addr']:05X} */")
    out += ["", "#endif", ""]
    _write(inc / "PROTOS.H", "\n".join(out))

    from . import fileheaders           # per-file headers (the game sources use these)
    missing = fileheaders.generate(con)
    if missing:
        print("warning: no source defines " + ", ".join(missing[:12]) + (" ..." if len(missing) > 12 else ""))

    structs = inc / "STRUCTS.H"
    if structs.exists():
        text = structs.read_text(errors="replace")
        if text.rstrip().rsplit("\n", 1)[-1].strip() != "#endif":
            raise SystemExit("src/include/STRUCTS.H: something was added after the closing #endif; "
                             "move it inside the include guard")
    if not structs.exists():
        structs.write_text("/* STRUCTS.H - shared struct types. Hand-written source: one definition per type. */\n"
                           "#ifndef STRUCTS_H\n#define STRUCTS_H\n\n#endif\n")


def _write(path, text):
    data = text.replace("\n", "\r\n").encode("latin-1")
    if path.exists() and path.read_bytes() == data:
        return
    # Write-then-rename: parallel `sr` runs regenerate the headers while others compile.
    tmp = path.with_name(f".{path.name}.{os.getpid()}")
    tmp.write_bytes(data)
    os.replace(tmp, path)
